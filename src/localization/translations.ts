/**
 * Global translation retrieval helper with fallback to English
 */
export const t = (key: string, lang: LanguageCode, fallback?: string): string => {
  const langObj = translations[lang] || translations.en;
  if (langObj && langObj[key]) {
    return langObj[key];
  }
  if (translations.en && translations.en[key]) {
    return translations.en[key];
  }
  return fallback || key;
};

